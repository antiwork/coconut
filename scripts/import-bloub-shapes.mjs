// Run with Node 22.13 or later: node scripts/import-bloub-shapes.mjs <Bloub checkout>
import { stripTypeScriptTypes } from 'node:module';
import { mkdtemp, readFile, writeFile, rm, mkdir } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { resolve, join } from 'node:path';
import { pathToFileURL, fileURLToPath } from 'node:url';
import { execFileSync } from 'node:child_process';

const source = resolve(process.argv[2]);
const root = fileURLToPath(new URL('../', import.meta.url));
const temporary = await mkdtemp(join(tmpdir(), 'coconut-shapes-'));
try {
  for (const name of ['math', 'profiles', 'shape', 'skins']) {
    const code = await readFile(join(source, 'src/bot', `${name}.ts`), 'utf8');
    const js = stripTypeScriptTypes(code).replace(/from '(\.\/[^']+)'/g, "from '$1.mjs'");
    await writeFile(join(temporary, `${name}.mjs`), js);
  }
  const { SHAPES } = await import(pathToFileURL(join(temporary, 'skins.mjs')));
  const revision = execFileSync('git', ['-C', source, 'rev-parse', 'HEAD'], { encoding: 'utf8' }).trim();
  const names = { cercle: 'round', galet: 'oval', squircle: 'square', capsule: 'wide',
    triangle: 'triangle', hexagone: 'hexagon', nuage: 'bean', goutte: 'pointed' };
  const profiles = SHAPES.map(({ id, radii }) => {
    const rows = Array.from({ length: 8 }, (_, i) =>
      '            ' + radii.slice(i * 8, i * 8 + 8).map(r => r.toPrecision(17)).join(', '));
    return `        .${names[id]}: [\n${rows.join(',\n')}\n        ]`;
  });
  await writeFile(join(root, 'ios/Coconut/BotShapeProfiles.swift'),
    `// Generated by scripts/import-bloub-shapes.mjs. Do not edit the samples.\n` +
    `// Source: https://github.com/jeremy-prt/bloub/tree/${revision}\n` +
    `// Copyright (c) 2026 Jérémy Perret. MIT license: Resources/Bloub-LICENSE.txt.\n` +
    `enum BotShapeProfiles {\n    static let radii: [CoconutShape: [Double]] = [\n${profiles.join(',\n')}\n    ]\n}\n`);
  await mkdir(join(root, 'ios/Coconut/Resources'), { recursive: true });
  await writeFile(join(root, 'ios/Coconut/Resources/Bloub-LICENSE.txt'),
    await readFile(join(source, 'LICENSE')));
} finally {
  await rm(temporary, { recursive: true, force: true });
}
